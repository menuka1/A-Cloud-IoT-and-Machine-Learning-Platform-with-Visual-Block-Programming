'use strict';
const { TARGETS } = require('./catalog');
const { isNum, num, q, analyze } = require('./common');
const { I2C, SIM_JS } = require('./i2c-sensors');

function generateNode(P, ctx) {
  const T = TARGETS[ctx.target]; const A = analyze(P, T.board);
  const V = (n) => `V["${n}"]`;
  const opnd = (s) => (isNum(s) ? num(s) : V(String(s).trim()));
  const jsOp = (o) => (o === '==' ? '===' : o === '!=' ? '!==' : o);
  const one = (l, op, r) => `${opnd(l)} ${jsOp(op)} ${opnd(r)}`;
  const cond = (b) => ((b.join === 'and' || b.join === 'or') ? `(${one(b.left, b.op, b.right)}) ${b.join === 'and' ? '&&' : '||'} (${one(b.left2, b.op2, b.right2)})` : one(b.left, b.op, b.right));
  let rc = 0;
  const L = []; const out = (s = '') => L.push(s);
  const rnd = (a, b) => `(${a} + Math.random() * (${b} - ${a}))`;

  out(`// ${ctx.name} - generated by TronicIOT Builder (${T.label})`);
  out('// Run with Node.js 18 or newer:  node <this file>.   No packages to install. Hardware is simulated: pins print what they would do.');
  out('"use strict";'); out();
  out(`const SERVER = ${q(ctx.serverUrl)};`); out(`const TOKEN = ${q(ctx.token)};`); out(`const LOOP_S = ${Number(P.interval)};`);
  if (A.uptime) out('const T0 = Date.now();');
  out('const V = {' + [...A.vars].sort().map((n) => `"${n}": 0`).join(', ') + '};'); out();
  out('const sleep = (s) => new Promise((r) => setTimeout(r, s * 1000));');
  out('async function req(method, path, body) {');
  out('  try {'); out('    const r = await fetch(SERVER + path, { method, headers: { "X-Device-Token": TOKEN, "Content-Type": "application/json" }, body: body === undefined ? undefined : JSON.stringify(body), signal: AbortSignal.timeout(10000) });');
  out('    let data = null; try { data = await r.json(); } catch (e) {}'); out('    if (!r.ok) console.log("http error:", r.status, data && data.error);'); out('    return [r.status, data];');
  out('  } catch (e) { console.log("http error:", e.message); return [0, null]; }'); out('}');
  out('function clean(d) { const o = {}; for (const [k, v] of Object.entries(d)) if (Number.isFinite(v)) o[k] = Math.round(v * 10000) / 10000; return o; }'); out();
  out('// ---------------- simulated hardware ----------------');
  out('const sim = (msg) => console.log("[sim]", msg);');
  out('const hw = {');
  out('  dout: (p, v) => sim(`pin ${p} -> ${v ? "HIGH" : "LOW"}`),'); out('  pwm: (p, v) => sim(`pin ${p} PWM ${Math.max(0, Math.min(255, Math.round(v)))}/255`),');
  out('  din: () => (Math.random() < 0.5 ? 0 : 1),'); out('  adc: (p, raw) => { const pct = Math.random() * 100; return raw ? Math.round(pct * 40.95) : Math.round(pct * 10) / 10; },');
  out('  dht: () => [Math.round((20 + Math.random() * 10) * 10) / 10, Math.round((40 + Math.random() * 30) * 10) / 10],'); out('  ultra: () => Math.round((5 + Math.random() * 195) * 10) / 10,'); out('};'); out();
  if (A.ml) {
    out('async function mlPredict(modelId, inputs, key) {'); out('  const [code, data] = await req("POST", `/api/ml/models/${modelId}/predict`, { inputs: clean(inputs) });');
    out('  const v = code === 200 && data && data.output ? data.output[key] : undefined;'); out('  if (typeof v === "boolean") return v ? 1 : 0;'); out('  if (typeof v === "number") return v;'); out('  console.log("ml -> no result (HTTP " + code + ")");'); out('  return NaN;'); out('}'); out();
  }
  if (A.handlers) { out('function toNum(s) { s = String(s).trim().toLowerCase(); if (s === "on" || s === "true") return 1; if (s === "off" || s === "false") return 0; const n = parseFloat(s); return Number.isFinite(n) ? n : 0; }'); out(); }

  const i2cSensors = [...new Set([...A.i2c.values()].map((s) => s.sensor))];
  if (i2cSensors.length) { out('const rr = (a, b, d) => +(a + Math.random() * (b - a)).toFixed(d);'); out('hw.i2c = {'); for (const s of i2cSensors) out(`  ${s}: () => ${SIM_JS[s].replace(/\br\(/g, 'rr(')},`); out('};'); out(); }
  const i2cLines = (b, pad) => { const S = I2C[b.type.slice(4)]; return [`${pad}[${S.outs.map(([k]) => V(b[k])).join(', ')}] = hw.i2c.${b.type.slice(4)}();`]; };
  if (A.map) {
    out('function mapRange(v, inMin, inMax, outMin, outMax, limit) {'); out('  if (inMax === inMin) return NaN;'); out('  let r = outMin + (v - inMin) * (outMax - outMin) / (inMax - inMin);');
    out('  if (limit) { const lo = Math.min(outMin, outMax), hi = Math.max(outMin, outMax); r = Math.min(hi, Math.max(lo, r)); }'); out('  return r;'); out('}'); out();
  }
  const emit = (blocks, ind) => {
    const pad = '  '.repeat(ind); const o = [];
    for (const b of blocks) {
      if (b.type.startsWith('i2c_')) { o.push(...i2cLines(b, pad)); continue; }
      switch (b.type) {
        case 'read_analog': o.push(`${pad}${V(b.var)} = hw.adc(${b.pin}, ${b.mode === 'raw'});`); break;
        case 'read_digital': o.push(`${pad}${V(b.var)} = hw.din(${b.pin});`); break;
        case 'read_dht': o.push(`${pad}[${V(b.tvar)}, ${V(b.hvar)}] = hw.dht(${b.pin}, "${b.model}");`); break;
        case 'read_ultrasonic': o.push(`${pad}${V(b.var)} = hw.ultra(${b.trig}, ${b.echo});`); break;
        case 'read_random': o.push(`${pad}${V(b.var)} = Math.round(${rnd(num(b.min), num(b.max))} * 100) / 100;`); break;
        case 'write_digital': o.push(`${pad}hw.dout(${b.pin}, ${opnd(b.value)} >= 0.5);`); break;
        case 'write_pwm': o.push(`${pad}hw.pwm(${b.pin}, ${opnd(b.value)});`); break;
        case 'set_var': o.push(`${pad}${V(b.var)} = ${opnd(b.value)};`); break;
        case 'change_var': o.push(`${pad}${V(b.var)} += ${opnd(b.by)};`); break;
        case 'wait': o.push(`${pad}await sleep(${num(b.seconds)});`); break;
        case 'if': o.push(`${pad}if (${cond(b)}) {`, ...emit(b.then, ind + 1)); if (b.else.length) o.push(`${pad}} else {`, ...emit(b.else, ind + 1)); o.push(`${pad}}`); break;
        case 'send_cloud': o.push(`${pad}{ const [code] = await req("POST", "/api/ingest", clean({ ${b.fields.map((f) => `${q(f.k)}: ${opnd(f.v)}`).join(', ')} })); console.log("send -> HTTP", code); }`); break;
        case 'ml_predict': o.push(`${pad}${V(b.var)} = await mlPredict(${parseInt(b.model, 10)}, { ${b.inputs.map((f) => `${q(f.k)}: ${opnd(f.v)}`).join(', ')} }, ${q(b.key)});`); break;
        case 'log': o.push(`${pad}console.log(${q(b.text)}${b.value && String(b.value).trim() ? `, ${opnd(b.value)}` : ''});`); break;
        case 'calc': { const l = opnd(b.left), r = opnd(b.right); o.push(`${pad}${V(b.var)} = ${b.op === '/' ? `(${r}) !== 0 ? (${l}) / (${r}) : NaN` : b.op === '%' ? `(${r}) !== 0 ? (${l}) % (${r}) : NaN` : `${l} ${b.op} ${r}`};`); break; }
        case 'map_range': o.push(`${pad}${V(b.var)} = mapRange(${opnd(b.value)}, ${opnd(b.inMin)}, ${opnd(b.inMax)}, ${opnd(b.outMin)}, ${opnd(b.outMax)}, ${b.clamp === 'yes'});`); break;
        case 'repeat': { const n = rc++; o.push(`${pad}for (let i${n} = 0; i${n} < ${parseInt(b.times, 10)}; i${n}++) {`, ...emit(b.body, ind + 1), `${pad}}`); break; }
        case 'read_uptime': o.push(`${pad}${V(b.var)} = (Date.now() - T0) / 1000;`); break;
        case 'comment': o.push(`${pad}// ${b.text}`); break;
        default: break;
      }
    }
    return o;
  };
  if (A.handlers) {
    out('async function handleCommand(name) {');
    P.handlers.forEach((h, i) => { out(`  ${i ? '} else ' : ''}if (name === ${q(h.name)}) {`); emit(h.body, 2).forEach((l) => out(l)); }); out('  }'); out('}'); out();
    out('async function pollCommands() {'); out('  const [code, data] = await req("GET", "/api/device/commands");'); out('  if (code === 200 && data) for (const c of data.commands || []) { V["cmd_value"] = toNum(c.value); console.log("command:", c.name); await handleCommand(c.name); }'); out('}'); out();
  }
  out('async function setup() {'); emit(P.setup, 1).forEach((l) => out(l)); out('}'); out();
  out('async function loopBody() {'); emit(P.loop, 1).forEach((l) => out(l)); out('}'); out();
  out('(async () => {'); out('  await setup();'); out('  for (;;) {'); out('    await loopBody();'); if (A.handlers) out('    await pollCommands();'); out('    await sleep(LOOP_S);'); out('  }'); out('})();');
  return L.join('\n') + '\n';
}
module.exports = { generateNode };
