'use strict';
const { TARGETS, BOARDS } = require('./catalog');
const { isNum, num, q, analyze } = require('./common');
const { I2C } = require('./i2c-sensors');

function generateArduino(P, ctx) {
  const T = TARGETS[ctx.target]; const board = T.board; const A = analyze(P, board);
  const https = ctx.serverUrl.startsWith('https://'); const poll = A.handlers;
  const invLed = (pin) => board === 'esp8266' && String(pin) === 'LED';
  const pin = (p) => (String(p) === 'LED' ? 'LED_BUILTIN' : String(p));
  const V = (n) => 'v_' + n;
  const opnd = (s) => (isNum(s) ? num(s) : V(String(s).trim()));
  const one = (l, op, r) => `${opnd(l)} ${op} ${opnd(r)}`;
  const cond = (b) => ((b.join === 'and' || b.join === 'or') ? `(${one(b.left, b.op, b.right)}) ${b.join === 'and' ? '&&' : '||'} (${one(b.left2, b.op2, b.right2)})` : one(b.left, b.op, b.right));
  let rc = 0;
  const L = []; const out = (s = '') => L.push(s);

  // ---------- header ----------
  out(`// ${ctx.name} - generated by TronicIOT Builder (${T.label})`);
  out('// Do not rename the sketch folder to something starting with a number. Libraries needed: see notes.');
  if (board === 'esp8266') { out('#include <ESP8266WiFi.h>'); out('#include <ESP8266HTTPClient.h>'); out('#include <WiFiClient.h>'); } else { out('#include <WiFi.h>'); out('#include <HTTPClient.h>'); }
  if (https) out('#include <WiFiClientSecure.h>');
  out('#include <ArduinoJson.h>');
  if (A.dht.size) out('#include <DHT.h>');
  // ---- I2C sensors (standard Arduino libraries) ----
  const I2CX = (s) => {
    const a = s.addr; const n = `${s.sensor}_${a.slice(2).toLowerCase()}`; const kind = s.sensor === 'htu21' ? (s.model === 'si7021' ? 'si7021' : 'htu21d') : s.sensor;
    const T = {
      bme280: { inc: 'Adafruit_BME280.h', decl: `Adafruit_BME280 ${n};`, begin: `${n}_ok = ${n}.begin(${a});`, name: 'BME280' },
      bmp280: { inc: 'Adafruit_BMP280.h', decl: `Adafruit_BMP280 ${n};`, begin: `${n}_ok = ${n}.begin(${a});`, name: 'BMP280' },
      bh1750: { inc: 'BH1750.h', decl: `BH1750 ${n}(${a});`, begin: `${n}_ok = ${n}.begin(BH1750::CONTINUOUS_HIGH_RES_MODE);`, name: 'BH1750' },
      aht: { inc: 'Adafruit_AHTX0.h', decl: `Adafruit_AHTX0 ${n};`, begin: `${n}_ok = ${n}.begin();`, name: 'AHT10/AHT20' },
      sht3x: { inc: 'Adafruit_SHT31.h', decl: `Adafruit_SHT31 ${n};`, begin: `${n}_ok = ${n}.begin(${a});`, name: 'SHT3x' },
      htu21d: { inc: 'Adafruit_HTU21DF.h', decl: `Adafruit_HTU21DF ${n};`, begin: `${n}_ok = ${n}.begin();`, name: 'HTU21D' },
      si7021: { inc: 'Adafruit_Si7021.h', decl: `Adafruit_Si7021 ${n} = Adafruit_Si7021();`, begin: `${n}_ok = ${n}.begin();`, name: 'Si7021' },
      mcp9808: { inc: 'Adafruit_MCP9808.h', decl: `Adafruit_MCP9808 ${n};`, begin: `${n}_ok = ${n}.begin(${a});`, name: 'MCP9808' },
      mpu6050: { inc: 'Adafruit_MPU6050.h', decl: `Adafruit_MPU6050 ${n};`, begin: `${n}_ok = ${n}.begin(${a});`, name: 'MPU6050' },
    }[kind];
    return { n, kind, ...T, a };
  };
  const i2cList = [...A.i2c.values()].map(I2CX);
  if (i2cList.length) { out('#include <Wire.h>'); for (const inc of new Set(i2cList.map((x) => x.inc))) out(`#include <${inc}>`); }
  out();
  out(`const char* WIFI_SSID = ${q(ctx.ssid)};`); out(`const char* WIFI_PASS = ${q(ctx.pass)};`);
  out(`const String SERVER = ${q(ctx.serverUrl)};`); out(`const char* TOKEN = ${q(ctx.token)};`);
  out(`const unsigned long LOOP_MS = ${Math.round(P.interval * 1000)}UL;`);
  out();
  out('WiFiClient plainClient;'); if (https) out('WiFiClientSecure secureClient;');
  out();
  for (const n of [...A.vars].sort()) out(`float ${V(n)} = 0;`);
  for (const [k, d] of A.dht) out(`DHT dht_${k}(${pin(d.pin)}, DHT${d.model});`);
  for (const x of i2cList) { out(x.decl); out(`bool ${x.n}_ok = false;`); }
  out();

  // ---------- helpers ----------
  out('void wifiConnect() {');
  out('  WiFi.mode(WIFI_STA);'); out('  WiFi.begin(WIFI_SSID, WIFI_PASS);');
  out('  Serial.print("Connecting to Wi-Fi");'); out('  unsigned long t0 = millis();');
  out('  while (WiFi.status() != WL_CONNECTED && millis() - t0 < 20000UL) { delay(250); Serial.print("."); }');
  out('  if (WiFi.status() == WL_CONNECTED) { Serial.println(); Serial.print("Connected, IP: "); Serial.println(WiFi.localIP()); }');
  out('  else { Serial.println(); Serial.println("Wi-Fi failed - will retry"); }'); out('}'); out();
  out('bool httpBegin(HTTPClient& http, const String& path) {');
  out('  http.setTimeout(8000);');
  out(`  return http.begin(${https ? 'secureClient' : 'plainClient'}, SERVER + path);`); out('}'); out();
  out('String jn(float v) { return (isnan(v) || isinf(v)) ? String("null") : String(v, 4); }'); out();
  if (A.send) {
    out('bool sendCloud(const String& json) {');
    out('  if (WiFi.status() != WL_CONNECTED) return false;');
    out('  HTTPClient http;'); out('  if (!httpBegin(http, "/api/ingest")) return false;');
    out('  http.addHeader("Content-Type", "application/json");'); out('  http.addHeader("X-Device-Token", TOKEN);');
    out('  int code = http.POST(json);'); out('  http.end();');
    out('  Serial.println(String("send -> HTTP ") + code);'); out('  return code == 200;'); out('}'); out();
  }
  if (A.ml) {
    out('float mlPredict(int modelId, const String& inputsJson, const char* key) {');
    out('  if (WiFi.status() != WL_CONNECTED) return NAN;');
    out('  HTTPClient http;'); out('  if (!httpBegin(http, "/api/ml/models/" + String(modelId) + "/predict")) return NAN;');
    out('  http.addHeader("Content-Type", "application/json");'); out('  http.addHeader("X-Device-Token", TOKEN);');
    out('  int code = http.POST("{\\"inputs\\":" + inputsJson + "}");'); out('  float result = NAN;');
    out('  if (code == 200) {');
    out('    JsonDocument doc;'); out('    if (!deserializeJson(doc, http.getString())) {');
    out('      JsonVariant v = doc["output"][key];'); out('      if (v.is<bool>()) result = v.as<bool>() ? 1.0f : 0.0f;'); out('      else if (v.is<float>()) result = v.as<float>();'); out('    }'); out('  } else { Serial.println(String("ml -> HTTP ") + code); }');
    out('  http.end();'); out('  return result;'); out('}'); out();
  }
  if (A.ultra) {
    out('float readUltrasonic(int trig, int echo) {');
    out('  digitalWrite(trig, LOW); delayMicroseconds(2);'); out('  digitalWrite(trig, HIGH); delayMicroseconds(10); digitalWrite(trig, LOW);');
    out('  unsigned long d = pulseIn(echo, HIGH, 30000UL);'); out('  if (d == 0) return NAN;'); out('  return d * 0.0343f / 2.0f;'); out('}'); out();
  }
  if (poll) {
    out('float parseCmdValue(String s) {'); out('  s.trim(); s.toLowerCase();'); out('  if (s == "on" || s == "true") return 1;'); out('  if (s == "off" || s == "false") return 0;'); out('  return s.toFloat();'); out('}'); out();
  }

  if (A.map) {
    out('float mapRange(float v, float inMin, float inMax, float outMin, float outMax, bool limit) {');
    out('  if (inMax == inMin) return NAN;'); out('  float r = outMin + (v - inMin) * (outMax - outMin) / (inMax - inMin);');
    out('  if (limit) { float lo = outMin < outMax ? outMin : outMax; float hi = outMin < outMax ? outMax : outMin; if (r < lo) r = lo; if (r > hi) r = hi; }');
    out('  return r;'); out('}'); out();
  }
  const i2cLines = (b, pad) => {
    const x = I2CX({ sensor: b.type.slice(4), addr: b.addr, model: b.model }); const ok = `${x.n}_ok`; const set = (k, expr) => `${pad}${V(b[k])} = ${ok} ? ${expr} : NAN;`;
    switch (x.kind) {
      case 'bme280': return [set('tvar', `${x.n}.readTemperature()`), set('hvar', `${x.n}.readHumidity()`), set('pvar', `${x.n}.readPressure() / 100.0f`)];
      case 'bmp280': return [set('tvar', `${x.n}.readTemperature()`), set('pvar', `${x.n}.readPressure() / 100.0f`)];
      case 'bh1750': return [`${pad}{ float lx = ${ok} ? ${x.n}.readLightLevel() : NAN; ${V(b.var)} = lx < 0 ? NAN : lx; }`];
      case 'aht': return [`${pad}{ sensors_event_t eh, et; if (${ok} && ${x.n}.getEvent(&eh, &et)) { ${V(b.tvar)} = et.temperature; ${V(b.hvar)} = eh.relative_humidity; } else { ${V(b.tvar)} = NAN; ${V(b.hvar)} = NAN; } }`];
      case 'sht3x': case 'htu21d': case 'si7021': return [set('tvar', `${x.n}.readTemperature()`), set('hvar', `${x.n}.readHumidity()`)];
      case 'mcp9808': return [set('tvar', `${x.n}.readTempC()`)];
      case 'mpu6050': return [`${pad}{ sensors_event_t ea, eg, et; if (${ok} && ${x.n}.getEvent(&ea, &eg, &et)) { ${V(b.axvar)} = ea.acceleration.x / 9.80665f; ${V(b.ayvar)} = ea.acceleration.y / 9.80665f; ${V(b.azvar)} = ea.acceleration.z / 9.80665f; ${V(b.gxvar)} = eg.gyro.x * 57.29578f; ${V(b.gyvar)} = eg.gyro.y * 57.29578f; ${V(b.gzvar)} = eg.gyro.z * 57.29578f; ${V(b.tvar)} = et.temperature; } else { ${[b.axvar, b.ayvar, b.azvar, b.gxvar, b.gyvar, b.gzvar, b.tvar].map((v) => V(v) + ' = NAN;').join(' ')} } }`];
      default: return [];
    }
  };
  // ---------- block emitter ----------
  const emit = (blocks, ind) => {
    const pad = '  '.repeat(ind); const o = [];
    for (const b of blocks) {
      if (b.type.startsWith('i2c_')) { o.push(...i2cLines(b, pad)); continue; }
      switch (b.type) {
        case 'read_analog': { const raw = `analogRead(${board === 'esp8266' ? 'A0' : pin(b.pin)})`; o.push(`${pad}${V(b.var)} = ${b.mode === 'raw' ? `(float)${raw}` : `${raw} * 100.0f / ${BOARDS[board].adcMax}.0f`};`); break; }
        case 'read_digital': o.push(`${pad}${V(b.var)} = digitalRead(${pin(b.pin)});`); break;
        case 'read_dht': o.push(`${pad}${V(b.tvar)} = dht_${b.pin}_${b.model}.readTemperature();`, `${pad}${V(b.hvar)} = dht_${b.pin}_${b.model}.readHumidity();`); break;
        case 'read_ultrasonic': o.push(`${pad}${V(b.var)} = readUltrasonic(${pin(b.trig)}, ${pin(b.echo)});`); break;
        case 'read_random': o.push(`${pad}${V(b.var)} = (float)random((long)(${num(b.min)} * 100), (long)(${num(b.max)} * 100) + 1) / 100.0f;`); break;
        case 'write_digital': o.push(`${pad}digitalWrite(${pin(b.pin)}, ${opnd(b.value)} >= 0.5 ? ${invLed(b.pin) ? 'LOW' : 'HIGH'} : ${invLed(b.pin) ? 'HIGH' : 'LOW'});`); break;
        case 'write_pwm': o.push(`${pad}analogWrite(${pin(b.pin)}, ${invLed(b.pin) ? '255 - ' : ''}(int)(constrain(${opnd(b.value)}, 0, 255) + 0.5f));`); break;
        case 'set_var': o.push(`${pad}${V(b.var)} = ${opnd(b.value)};`); break;
        case 'change_var': o.push(`${pad}${V(b.var)} += ${opnd(b.by)};`); break;
        case 'wait': o.push(`${pad}delay(${Math.round(b.seconds * 1000)});`); break;
        case 'if':
          o.push(`${pad}if (${cond(b)}) {`, ...emit(b.then, ind + 1));
          if (b.else.length) o.push(`${pad}} else {`, ...emit(b.else, ind + 1));
          o.push(`${pad}}`); break;
        case 'send_cloud':
          o.push(`${pad}{`, `${pad}  String j = "{";`);
          b.fields.forEach((f, i) => o.push(`${pad}  j += ${q((i ? ',' : '') + `"${f.k}":`)} + jn(${opnd(f.v)});`));
          o.push(`${pad}  j += "}";`, `${pad}  sendCloud(j);`, `${pad}}`); break;
        case 'ml_predict':
          o.push(`${pad}{`, `${pad}  String j = "{";`);
          b.inputs.forEach((f, i) => o.push(`${pad}  j += ${q((i ? ',' : '') + `"${f.k}":`)} + jn(${opnd(f.v)});`));
          o.push(`${pad}  j += "}";`, `${pad}  ${V(b.var)} = mlPredict(${parseInt(b.model, 10)}, j, ${q(b.key)});`, `${pad}}`); break;
        case 'log': o.push(`${pad}Serial.print(${q(b.text)});`, ...(b.value && String(b.value).trim() ? [`${pad}Serial.print(" "); Serial.println(${opnd(b.value)});`] : [`${pad}Serial.println();`])); break;
        case 'calc': { const l = opnd(b.left), r = opnd(b.right); o.push(`${pad}${V(b.var)} = ${b.op === '/' ? `(${r}) != 0 ? (float)(${l}) / (${r}) : NAN` : b.op === '%' ? `(${r}) != 0 ? fmod(${l}, ${r}) : NAN` : `${l} ${b.op} ${r}`};`); break; }
        case 'map_range': o.push(`${pad}${V(b.var)} = mapRange(${opnd(b.value)}, ${opnd(b.inMin)}, ${opnd(b.inMax)}, ${opnd(b.outMin)}, ${opnd(b.outMax)}, ${b.clamp === 'yes'});`); break;
        case 'repeat': { const n = rc++; o.push(`${pad}for (int rep${n} = 0; rep${n} < ${parseInt(b.times, 10)}; rep${n}++) {`, ...emit(b.body, ind + 1), `${pad}}`); break; }
        case 'read_uptime': o.push(`${pad}${V(b.var)} = millis() / 1000.0f;`); break;
        case 'comment': o.push(`${pad}// ${b.text}`); break;
        default: break;
      }
    }
    return o;
  };

  // ---------- command handler ----------
  if (poll) {
    out('void handleCommand(const String& name) {');
    P.handlers.forEach((h, i) => { out(`  ${i ? 'else ' : ''}if (name == ${q(h.name)}) {`); emit(h.body, 2).forEach((l) => out(l)); out('  }'); });
    out('}'); out();
    out('void pollCommands() {');
    out('  if (WiFi.status() != WL_CONNECTED) return;');
    out('  HTTPClient http;'); out('  if (!httpBegin(http, "/api/device/commands")) return;');
    out('  http.addHeader("X-Device-Token", TOKEN);');
    out('  if (http.GET() == 200) {');
    out('    JsonDocument doc;'); out('    if (!deserializeJson(doc, http.getString())) {');
    out('      for (JsonObject c : doc["commands"].as<JsonArray>()) {');
    out('        String name = c["name"].as<String>();'); out('        v_cmd_value = parseCmdValue(c["value"].as<String>());');
    out('        Serial.println("command: " + name);'); out('        handleCommand(name);'); out('      }'); out('    }'); out('  }');
    out('  http.end();'); out('}'); out();
  }

  // ---------- setup / loop ----------
  out('void setup() {'); out('  Serial.begin(115200);'); out('  delay(300);');
  if (board === 'esp8266') out('  analogWriteRange(255);'); else out('  analogReadResolution(12);');
  for (const p of A.outs) { out(`  pinMode(${pin(p)}, OUTPUT);`); if (invLed(p)) out(`  digitalWrite(${pin(p)}, HIGH);`); }
  for (const p of A.pwm) { out(`  pinMode(${pin(p)}, OUTPUT);`); }
  for (const [p, up] of A.ins) out(`  pinMode(${pin(p)}, ${up ? 'INPUT_PULLUP' : 'INPUT'});`);
  for (const k of A.dht.keys()) out(`  dht_${k}.begin();`);
  if (i2cList.length) { out('  Wire.begin();   // default I2C pins of your board'); for (const x of i2cList) { out(`  ${x.begin}`); out(`  if (!${x.n}_ok) Serial.println("${x.name} not found at ${x.a} - check wiring and address");`); } }
  if (https) out('  secureClient.setInsecure();   // skips certificate check; fine for a hobby server, see notes for production');
  out('  wifiConnect();');
  emit(P.setup, 1).forEach((l) => out(l));
  out('}'); out();
  out('void loop() {');
  out('  if (WiFi.status() != WL_CONNECTED) wifiConnect();');
  emit(P.loop, 1).forEach((l) => out(l));
  if (poll) out('  pollCommands();');
  out('  delay(LOOP_MS);'); out('}');
  return L.join('\n') + '\n';
}
module.exports = { generateArduino };
