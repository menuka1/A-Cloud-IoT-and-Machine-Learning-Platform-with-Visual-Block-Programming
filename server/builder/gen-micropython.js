'use strict';
const { TARGETS } = require('./catalog');
const { isNum, num, q, analyze } = require('./common');
const { I2C, pythonDrivers } = require('./i2c-sensors');

function generateMicroPython(P, ctx) {
  const T = TARGETS[ctx.target]; const board = T.board; const A = analyze(P, board);
  const V = (n) => `V["${n}"]`;
  const opnd = (s) => (isNum(s) ? num(s) : V(String(s).trim()));
  const one = (l, op, r) => `${opnd(l)} ${op} ${opnd(r)}`;
  const cond = (b) => ((b.join === 'and' || b.join === 'or') ? `(${one(b.left, b.op, b.right)}) ${b.join === 'and' ? 'and' : 'or'} (${one(b.left2, b.op2, b.right2)})` : one(b.left, b.op, b.right));
  let rc = 0;
  const pinLit = (p) => { p = String(p); if (p === 'LED') return board === 'picow' ? '"LED"' : '2'; if (p === 'A0') return '0'; return p; };
  const invLed = (p) => board === 'esp8266' && String(p) === 'LED';
  const L = []; const out = (s = '') => L.push(s);

  out(`# ${ctx.name} - generated by TronicIOT Builder (${T.label})`);
  out('# Save this file on the board as main.py (Thonny: File > Save as > MicroPython device).');
  out('import network, time, json, machine');
  if (A.math) out('import math');
  out('try:'); out('    import urequests as requests'); out('except ImportError:'); out('    import requests');
  if (A.dht.size) out('import dht');
  if (A.random) { out('try:'); out('    import urandom as random'); out('except ImportError:'); out('    import random'); }
  out();
  out(`WIFI_SSID = ${q(ctx.ssid)}`); out(`WIFI_PASS = ${q(ctx.pass)}`); out(`SERVER = ${q(ctx.serverUrl)}`); out(`TOKEN = ${q(ctx.token)}`); out(`LOOP_S = ${Number(P.interval)}`);
  out('HEADERS = {"X-Device-Token": TOKEN, "Content-Type": "application/json"}');
  out('NAN = float("nan")'); if (A.uptime) out('T0 = time.time()');
  out(); out('V = {' + [...A.vars].sort().map((n) => `"${n}": 0.0`).join(', ') + '}');
  out('_P = {}'); out('wlan = network.WLAN(network.STA_IF)'); out();

  out('def wifi_connect():');
  out('    wlan.active(True)'); out('    if wlan.isconnected():'); out('        return True');
  out('    print("Connecting to Wi-Fi...")'); out('    wlan.connect(WIFI_SSID, WIFI_PASS)');
  out('    for _ in range(40):'); out('        if wlan.isconnected():'); out('            print("Connected:", wlan.ifconfig()[0])'); out('            return True'); out('        time.sleep(0.5)');
  out('    print("Wi-Fi failed - will retry")'); out('    return False'); out();
  out('def req(method, path, body=None):');
  out('    try:'); out('        if method == "POST":'); out('            r = requests.post(SERVER + path, data=json.dumps(body), headers=HEADERS)');
  out('        else:'); out('            r = requests.get(SERVER + path, headers=HEADERS)');
  out('        code = r.status_code'); out('        data = r.json() if code == 200 else None'); out('        r.close()'); out('        return code, data');
  out('    except Exception as e:'); out('        print("http error:", e)'); out('        return 0, None'); out();
  out('def clean(d):'); out('    return {k: round(v, 4) for k, v in d.items() if v - v == 0}  # drops NaN (failed sensor reads)'); out();
  out('def pin_out(p):'); out('    k = ("o", p)'); out('    if k not in _P:'); out('        _P[k] = machine.Pin(p, machine.Pin.OUT)');
  if (A.outs.size && [...A.outs].some(invLed)) out('        _P[k].value(1)  # inverted onboard LED: start OFF');
  out('    return _P[k]'); out();
  if (A.ins.size) { out('def pin_in(p, pull):'); out('    k = ("i", p)'); out('    if k not in _P:'); out('        _P[k] = machine.Pin(p, machine.Pin.IN, machine.Pin.PULL_UP) if pull else machine.Pin(p, machine.Pin.IN)'); out('    return _P[k]'); out(); }
  if (A.pwm.size) {
    out('def pwm_set(p, level, inverted=False):'); out('    level = int(max(0, min(255, level)) + 0.5)'); out('    if inverted:'); out('        level = 255 - level'); out('    k = ("p", p)');
    out('    if k not in _P:'); out('        _P[k] = machine.PWM(machine.Pin(p), freq=1000)');
    out(board === 'esp8266' ? '    _P[k].duty(int(level * 1023 / 255))' : '    _P[k].duty_u16(int(level * 257))'); out();
  }
  if (A.analog) {
    out('def adc_percent(p):'); out('    k = ("a", p)'); out('    if k not in _P:');
    if (board === 'esp32') { out('        _P[k] = machine.ADC(machine.Pin(p))'); out('        _P[k].atten(machine.ADC.ATTN_11DB)'); }
    else out(board === 'esp8266' ? '        _P[k] = machine.ADC(0)' : '        _P[k] = machine.ADC(machine.Pin(p))');
    out('    return _P[k].read_u16() * 100.0 / 65535'); out();
    out('def adc_raw(p):'); out('    return adc_percent(p) * 65535 / 100.0'); out();
  }
  if (A.dht.size) {
    out('def read_dht(p, model):'); out('    k = ("d", p, model)'); out('    if k not in _P:'); out('        _P[k] = dht.DHT11(machine.Pin(p)) if model == "11" else dht.DHT22(machine.Pin(p))  # DHT21 / AM2301 speak the DHT22 protocol');
    out('    try:'); out('        _P[k].measure()'); out('        return _P[k].temperature(), _P[k].humidity()'); out('    except OSError:'); out('        return NAN, NAN'); out();
  }
  if (A.ultra) {
    out('def read_ultrasonic(trig, echo):'); out('    t = pin_out(trig)'); out('    e = pin_in(echo, False)');
    out('    t.value(0); time.sleep_us(2); t.value(1); time.sleep_us(10); t.value(0)');
    out('    try:'); out('        d = machine.time_pulse_us(e, 1, 30000)'); out('    except OSError:'); out('        return NAN'); out('    return NAN if d < 0 else d * 0.0343 / 2'); out();
  }
  if (A.ml) {
    out('def ml_predict(model_id, inputs, key):'); out('    code, data = req("POST", "/api/ml/models/%d/predict" % model_id, {"inputs": clean(inputs)})');
    out('    if code == 200 and data:'); out('        v = data.get("output", {}).get(key)'); out('        if isinstance(v, bool):'); out('            return 1.0 if v else 0.0'); out('        if isinstance(v, (int, float)):'); out('            return float(v)');
    out('    else:'); out('        print("ml -> HTTP", code)'); out('    return NAN'); out();
  }
  if (A.handlers) {
    out('def to_num(s):'); out('    s = str(s).strip().lower()'); out('    if s in ("on", "true"):'); out('        return 1.0'); out('    if s in ("off", "false"):'); out('        return 0.0'); out('    try:'); out('        return float(s)'); out('    except ValueError:'); out('        return 0.0'); out();
  }

  const i2cSensors = [...new Set([...A.i2c.values()].map((s) => s.sensor))];
  if (i2cSensors.length) {
    out(`i2c = ${board === 'esp32' ? 'machine.I2C(0, scl=machine.Pin(22), sda=machine.Pin(21), freq=100000)' : board === 'esp8266' ? 'machine.I2C(scl=machine.Pin(5), sda=machine.Pin(4), freq=100000)' : 'machine.I2C(0, scl=machine.Pin(5), sda=machine.Pin(4), freq=100000)'}`);
    out('def i2c_w(addr, data):'); out('    i2c.writeto(addr, bytes(data))'); out('def i2c_r(addr, n):'); out('    return i2c.readfrom(addr, n)');
    out('def i2c_wm(addr, reg, data):'); out('    i2c.writeto_mem(addr, reg, bytes(data))'); out('def i2c_rm(addr, reg, n):'); out('    return i2c.readfrom_mem(addr, reg, n)'); out();
    out(pythonDrivers(i2cSensors));
  }
  const i2cLines = (b, pad) => { const S = I2C[b.type.slice(4)]; return [`${pad}[${S.outs.map(([k]) => V(b[k])).join(', ')}] = _drv_${S.pyFn}(${b.addr}${S.pyFn === 'aht' ? `, "${b.model}"` : ''})`]; };
  if (A.map) {
    out('def map_range(v, in_min, in_max, out_min, out_max, limit):'); out('    if in_max == in_min:'); out('        return NAN');
    out('    r = out_min + (v - in_min) * (out_max - out_min) / (in_max - in_min)'); out('    if limit:');
    out('        lo, hi = (out_min, out_max) if out_min <= out_max else (out_max, out_min)'); out('        r = lo if r < lo else (hi if r > hi else r)'); out('    return r'); out();
  }
  const emit = (blocks, ind) => {
    const pad = '    '.repeat(ind); const o = [];
    for (const b of blocks) {
      if (b.type.startsWith('i2c_')) { o.push(...i2cLines(b, pad)); continue; }
      switch (b.type) {
        case 'read_analog': o.push(`${pad}${V(b.var)} = ${b.mode === 'raw' ? 'adc_raw' : 'adc_percent'}(${pinLit(b.pin)})`); break;
        case 'read_digital': o.push(`${pad}${V(b.var)} = float(pin_in(${pinLit(b.pin)}, ${b.pull === 'up' ? 'True' : 'False'}).value())`); break;
        case 'read_dht': o.push(`${pad}${V(b.tvar)}, ${V(b.hvar)} = read_dht(${pinLit(b.pin)}, "${b.model}")`); break;
        case 'read_ultrasonic': o.push(`${pad}${V(b.var)} = read_ultrasonic(${pinLit(b.trig)}, ${pinLit(b.echo)})`); break;
        case 'read_random': o.push(`${pad}${V(b.var)} = ${num(b.min)} + (${num(b.max)} - ${num(b.min)}) * random.getrandbits(16) / 65535.0`); break;
        case 'write_digital': o.push(`${pad}pin_out(${pinLit(b.pin)}).value(${invLed(b.pin) ? '0 if' : '1 if'} ${opnd(b.value)} >= 0.5 else ${invLed(b.pin) ? '1' : '0'})`); break;
        case 'write_pwm': o.push(`${pad}pwm_set(${pinLit(b.pin)}, ${opnd(b.value)}, ${invLed(b.pin) ? 'True' : 'False'})`); break;
        case 'set_var': o.push(`${pad}${V(b.var)} = ${opnd(b.value)}`); break;
        case 'change_var': o.push(`${pad}${V(b.var)} += ${opnd(b.by)}`); break;
        case 'wait': o.push(`${pad}time.sleep(${num(b.seconds)})`); break;
        case 'if':
          o.push(`${pad}if ${cond(b)}:`); o.push(...(b.then.length ? emit(b.then, ind + 1) : [`${pad}    pass`]));
          if (b.else.length) { o.push(`${pad}else:`, ...emit(b.else, ind + 1)); } break;
        case 'send_cloud': o.push(`${pad}req("POST", "/api/ingest", clean({${b.fields.map((f) => `${q(f.k)}: ${opnd(f.v)}`).join(', ')}}))`); break;
        case 'ml_predict': o.push(`${pad}${V(b.var)} = ml_predict(${parseInt(b.model, 10)}, {${b.inputs.map((f) => `${q(f.k)}: ${opnd(f.v)}`).join(', ')}}, ${q(b.key)})`); break;
        case 'log': o.push(`${pad}print(${q(b.text)}${b.value && String(b.value).trim() ? `, ${opnd(b.value)}` : ''})`); break;
        case 'calc': { const l = opnd(b.left), r = opnd(b.right); o.push(`${pad}${V(b.var)} = ${b.op === '/' ? `(${l}) / (${r}) if (${r}) != 0 else NAN` : b.op === '%' ? `math.fmod(${l}, ${r}) if (${r}) != 0 else NAN` : `${l} ${b.op} ${r}`}`); break; }
        case 'map_range': o.push(`${pad}${V(b.var)} = map_range(${opnd(b.value)}, ${opnd(b.inMin)}, ${opnd(b.inMax)}, ${opnd(b.outMin)}, ${opnd(b.outMax)}, ${b.clamp === 'yes' ? 'True' : 'False'})`); break;
        case 'repeat': o.push(`${pad}for _ in range(${parseInt(b.times, 10)}):`, ...(b.body.length ? emit(b.body, ind + 1) : [`${pad}    pass`])); break;
        case 'read_uptime': o.push(`${pad}${V(b.var)} = time.time() - T0`); break;
        case 'comment': o.push(`${pad}# ${b.text}`); break;
        default: break;
      }
    }
    return o;
  };
  const body = (blocks, ind) => { const e = emit(blocks, ind); return e.length ? e : ['    '.repeat(ind) + 'pass']; };

  if (A.handlers) {
    out('def handle_command(name):');
    P.handlers.forEach((h, i) => { out(`    ${i ? 'elif' : 'if'} name == ${q(h.name)}:`); body(h.body, 2).forEach((l) => out(l)); });
    out(); out('def poll_commands():'); out('    code, data = req("GET", "/api/device/commands")'); out('    if code == 200 and data:');
    out('        for c in data.get("commands", []):'); out('            V["cmd_value"] = to_num(c.get("value"))'); out('            print("command:", c.get("name"))'); out('            handle_command(c.get("name"))'); out();
  }
  out('def setup():'); body(P.setup, 1).forEach((l) => out(l)); out();
  out('def main():'); out('    wifi_connect()'); out('    setup()'); out('    while True:'); out('        if not wlan.isconnected():'); out('            wifi_connect()');
  out('        loop_body()'); if (A.handlers) out('        poll_commands()'); out('        time.sleep(LOOP_S)'); out();
  // loop_body must be defined before main is *called* (not before it's defined) - emit it here, call main() last
  out('def loop_body():'); body(P.loop, 1).forEach((l) => out(l)); out();
  out('main()');
  return L.join('\n') + '\n';
}
module.exports = { generateMicroPython };
